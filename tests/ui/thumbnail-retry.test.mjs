import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';
const source = stripTypeScriptTypes(await readFile(new URL('../../ui-src/lib/thumbnailRetry.ts', import.meta.url), 'utf8'));
const {ThumbnailRetry} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);

test('retries resume promptly after the player closes without spending attempts while paused', t => {
  t.mock.timers.enable({apis:['setTimeout']});
  const requests=[];
  const retry = new ThumbnailRetry(request => requests.push(request), () => 0);
  retry.setReady(true);
  retry.error();
  t.mock.timers.tick(250);
  assert.deepEqual(requests,[1]);
  retry.error();
  retry.setReady(false);
  t.mock.timers.tick(30_000);
  assert.deepEqual(requests,[1], 'hidden cards and playback must not issue retries');
  retry.setReady(true);
  t.mock.timers.tick(249);
  assert.deepEqual(requests,[1]);
  t.mock.timers.tick(1);
  assert.deepEqual(requests,[1,2]);
  retry.dispose();
});
test('permanently missing images stop after a bounded burst and can recover on a later visit', t => {
  t.mock.timers.enable({apis:['setTimeout']});
  const requests=[];
  const retry = new ThumbnailRetry(request => {requests.push(request);retry.error();}, () => 1);
  retry.setReady(true);
  retry.error();
  for(let i=0;i<8;i++) t.mock.timers.tick(2000);
  assert.equal(requests.length,8);
  t.mock.timers.tick(60_000);
  assert.equal(requests.length,8, 'a bad image must not cause requests forever');
  retry.setReady(false);
  retry.setReady(true);
  t.mock.timers.tick(2000);
  assert.equal(requests.length,9);
  assert.equal(requests.at(-1),9, 'request URLs must remain unique across retry bursts');
  retry.dispose();
});
test('successful loads and obsolete revisions cancel pending retries', t => {
  t.mock.timers.enable({apis:['setTimeout']});
  const requests=[];
  const retry = new ThumbnailRetry(request => requests.push(request), () => 0);
  retry.setReady(true);
  retry.error();
  retry.error();
  retry.loaded();
  t.mock.timers.tick(2000);
  assert.deepEqual(requests,[]);
  retry.error();
  retry.dispose();
  retry.setReady(true);
  retry.error();
  t.mock.timers.tick(2000);
  assert.deepEqual(requests,[], 'unmount or thumbnail revision replacement must cancel the old controller');
});
